//! `spirolo init`: detect the stack and write a commented `.spirolorc.jsonc`.
//!
//! The written file explains every default in place, so a first run needs no
//! configuration and a reader understands what they are accepting. `init` refuses to
//! clobber an existing file without `--force`, and prints the detected stack — package
//! manager, tools with versions, setup files, aliases — in the summary style `list` uses.

use std::fmt::Write as _;
use std::path::Path;

use spirolo_model::{BuildOptions, Model};

use crate::detect::{self, Detection};
use crate::rc;

/// Run `spirolo init` against `root`. See the [module docs](self).
pub fn init(root: &Path, force: bool) -> u8 {
    let target = root.join(rc::FILE_NAME);
    if target.exists() && !force {
        eprintln!(
            "spirolo init: {} already exists; pass --force to overwrite",
            rc::FILE_NAME
        );
        return crate::EXIT_ERROR;
    }

    // Build the model so detection reads the runner configs' setup files exactly as `list`
    // does, rather than re-parsing them a second, divergent way.
    let model = Model::build_with(
        root,
        &BuildOptions::default(),
        &spirolo_frameworks::recognisers(),
    );
    let detection = detect::run(root, &model);

    if let Err(error) = std::fs::write(&target, render(&detection)) {
        eprintln!("spirolo init: cannot write {}: {error}", rc::FILE_NAME);
        return crate::EXIT_ERROR;
    }

    print!("{}", summary(&detection));
    crate::EXIT_OK
}

/// The commented `.spirolorc.jsonc`: a header recording what was detected, then the
/// documented keys, each with the guess `init` made and a comment explaining it.
fn render(detection: &Detection) -> String {
    // The detected line goes inside a `//` comment, so any newline a version string smuggled
    // out of package.json would break out of the comment and corrupt the file spirolo just
    // wrote. Flatten line breaks to keep the header — and the generated file — valid JSONC.
    let detected = detected_line(detection).replace(['\n', '\r'], " ");
    format!(
        "// spirolo configuration — generated by `spirolo init`.\n\
         // Detected: {detected}.\n\
         // Every key below is documented in place; delete a key to accept spirolo's default.\n\
         {}",
        body(detection),
    )
}

/// The documented body: every key preceded by the comment that explains it, with the
/// detected guess written in place. Best-effort guesses (`urlSources`, `dataLayer`,
/// `claims`) are written commented out, so every one is questionable in place and nothing
/// silently takes effect that spirolo only inferred.
fn body(detection: &Detection) -> String {
    let mut out = String::from("{\n");

    let _ = write!(
        out,
        "  // spirolo reads MSW/nock handlers only from files these globs match. Empty keeps the\n\
         \x20 // default: any file under a `mocks` or `msw` directory that imports the library.\n\
         \x20 // Detected from the handler files the model already found.\n\
         \x20 \"handlers\": {},\n\n",
        json_array(&detection.handler_globs),
    );

    let _ = write!(
        out,
        "  // The modules that own outbound network access — your API client, a fetch wrapper —\n\
         \x20 // so a rule can tell a mock of your own client from a mock of a third party. These\n\
         \x20 // are the specifiers this suite module-mocks most; uncomment the ones that are your\n\
         \x20 // data layer, and set the scope below to the tests the rule should judge.\n\
         \x20 \"dataLayer\": {},\n\n",
        candidate_array(&detection.data_layer),
    );

    let _ = write!(
        out,
        "  // Which test files `data-layer-mock` applies to: integration and container specs,\n\
         \x20 // where the network should answer, not a pure unit test that legitimately stubs a\n\
         \x20 // client. Globs, matched against the repo-relative path.\n\
         \x20 \"dataLayerScope\": {},\n\n",
        json_array(&default_data_layer_scope()),
    );

    let _ = write!(
        out,
        "  // The modules or JSON keys that define the base URLs your code calls, as `path#name`,\n\
         \x20 // so a rule can fold a handler pattern against the URL production emits. These are\n\
         \x20 // the constants and exports that read like a base URL; uncomment the real ones.\n\
         \x20 \"urlSources\": {},\n\n",
        candidate_array(&detection.url_sources),
    );

    let _ = write!(
        out,
        "  // Assumed values for named environment variables, read from this file only and never\n\
         \x20 // from your real environment, so a URL built from `process.env.API_VERSION` folds to\n\
         \x20 // a comparable path. Empty by default; add `\"API_VERSION\": \"v1\"` and its kin.\n\
         \x20 \"env\": {{}},\n\n",
    );

    let _ = write!(
        out,
        "  // Markdown files whose testing claims `gate-truth` diffs against the real config\n\
         \x20 // (for example \"mutation score is ratcheted\", \"thresholds enforced\"). These mention\n\
         \x20 // a gate; uncomment the ones that make a claim about this suite.\n\
         \x20 \"claims\": {},\n\n",
        candidate_array(&detection.claims),
    );

    let _ = write!(
        out,
        "  // Mutation reports spirolo reads for redundant-test, as globs relative to the root. The\n\
         \x20 // default reads Stryker's own report path under any package; detected reports are\n\
         \x20 // written in place. Delete a path to stop reading it.\n\
         \x20 \"inputs\": {{ \"mutation\": {} }},\n\n",
        mutation_globs(&detection.mutation_reports),
    );

    let _ = write!(
        out,
        "  // Rule severities. Every rule the binary runs is listed with its default; change a\n\
         \x20 // value to \"error\", \"warn\" or \"info\", or delete a line to keep the default.\n\
         \x20 \"rules\": {{\n{}\x20 }}\n",
        rules_block(&detection.rules),
    );

    out.push_str("}\n");
    out
}

/// The default `dataLayerScope`: integration and MSW specs, and anything under an
/// `integration` directory — the files where the network should answer, not a client stub.
fn default_data_layer_scope() -> Vec<String> {
    vec![
        "**/*.integration.*".to_owned(),
        "**/*.msw.*".to_owned(),
        "**/integration/**".to_owned(),
    ]
}

/// The live `inputs.mutation` value: the reports detected under the tree, or the default
/// report glob when none was found, so a first run reads a committed report either way.
fn mutation_globs(detected: &[String]) -> String {
    if detected.is_empty() {
        json_array(&[rc::DEFAULT_MUTATION_GLOB.to_owned()])
    } else {
        json_array(detected)
    }
}

/// A JSON array of strings on one line: `["a", "b"]`, or `[]` when empty.
fn json_array(items: &[String]) -> String {
    let quoted: Vec<String> = items.iter().map(|item| format!("{item:?}")).collect();
    format!("[{}]", quoted.join(", "))
}

/// An empty JSON array carrying each detected candidate as a commented-out element, so the
/// key reads as `[]` to the config reader — no guess silently takes effect — while a reader
/// accepts one by uncommenting it. Detection with no candidates writes a bare `[]` with a
/// note, so the reason the array is empty is in the file.
///
/// The result is valid JSONC: comments inside an array are allowed, and the array holds no
/// live elements, so the config round-trips with no diagnostics.
fn candidate_array(items: &[String]) -> String {
    if items.is_empty() {
        return "[\n    // (spirolo found no candidates to propose)\n  ]".to_owned();
    }
    let mut out = String::from("[\n");
    for item in items {
        let _ = writeln!(out, "    // {item:?}");
    }
    out.push_str("  ]");
    out
}

/// The `rules` block's body: one `"name": "severity",` line per registered rule, indented,
/// in registry order. Every line carries a trailing comma — valid JSONC, and correct
/// between entries — so more than one rule still parses.
fn rules_block(rules: &[detect::RuleDefault]) -> String {
    let mut out = String::new();
    for rule in rules {
        let _ = writeln!(out, "    {:?}: {:?},", rule.name, rule.severity);
    }
    out
}

/// The detected stack as one line — `pnpm · vitest 2.1.9 · msw 2.4.11` — or a note that
/// nothing was found, for the file header.
fn detected_line(detection: &Detection) -> String {
    let mut parts = Vec::new();
    if let Some(manager) = detection.package_manager {
        parts.push(manager.to_owned());
    }
    parts.extend(detection.tools.iter().map(tool_display));
    if parts.is_empty() {
        "nothing (no lockfile, no known test tooling)".to_owned()
    } else {
        parts.join(" · ")
    }
}

/// The fallow-style summary printed after writing: the version line, then what was found.
fn summary(detection: &Detection) -> String {
    let mut out = format!(
        "spirolo {} · init · {}\n",
        env!("CARGO_PKG_VERSION"),
        detection.package_manager.unwrap_or("no lockfile"),
    );
    let tools = if detection.tools.is_empty() {
        "none".to_owned()
    } else {
        join(detection.tools.iter().map(tool_display))
    };
    let _ = writeln!(out, "detected  {tools}");
    if !detection.setup_files.is_empty() {
        let _ = writeln!(out, "setup     {}", detection.setup_files.join(" · "));
    }
    if !detection.aliases.is_empty() {
        let aliases = join(
            detection
                .aliases
                .iter()
                .map(|alias| format!("{} → {}", alias.pattern, alias.target)),
        );
        let _ = writeln!(out, "aliases   {aliases}");
    }
    let _ = writeln!(out, "wrote     {}", rc::FILE_NAME);
    out
}

/// One tool as `name version`.
fn tool_display(tool: &detect::Tool) -> String {
    format!("{} {}", tool.name, tool.version)
}

/// Join an iterator of strings with the summary's ` · ` separator.
fn join(parts: impl Iterator<Item = String>) -> String {
    parts.collect::<Vec<_>>().join(" · ")
}
