//! Node-kind codes for the body hash, frozen at oxc 0.110's `AstType` numbering.
//!
//! The body hash (see [`crate::analysis`]) writes one byte per AST node. Writing
//! `AstType as u8` tied every hash, and so every `duplicate-test` finding id and every
//! ratchet baseline, to one oxc release: oxc renumbers its kinds as it adds them. This
//! table pins the byte to the numbering the hashes were first recorded under. A kind oxc
//! later split out of an older one keeps the older one's code; the match is exhaustive,
//! so the next bump that adds a kind fails to compile here instead of moving hashes.

